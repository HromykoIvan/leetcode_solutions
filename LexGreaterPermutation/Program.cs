// LeetCode. Lexicographically Smallest Permutation Strictly Greater Than target.
//
// ЗАДАЧА:
// Дана строка s (набор букв, из которых можно составлять перестановки) и строка target,
// обе длины n. Нужно вернуть ЛЕКСИКОГРАФИЧЕСКИ НАИМЕНЬШУЮ перестановку букв s, которая
// СТРОГО БОЛЬШЕ target. Если такой нет — вернуть "".
//
// ─────────────────────────────────────────────────────────────────────────────
// ГЛАВНАЯ ИДЕЯ
// ─────────────────────────────────────────────────────────────────────────────
// s задаёт МУЛЬТИМНОЖЕСТВО букв (сколько какой буквы доступно). Порядок в s не важен —
// важны только частоты. Поэтому первым делом считаем counts[26].
//
// Строим ответ ПОЗИЦИЯ ЗА ПОЗИЦИЕЙ. Чтобы результат был СТРОГО больше target и при этом
// МИНИМАЛЬНЫМ, действуем жадно:
//
//   1) Как можно ДОЛЬШЕ держим префикс РАВНЫМ target.
//      Пока на позиции i доступна буква == target[i] — ставим её и идём дальше.
//      Чем длиннее совпавший префикс, тем меньше итоговая строка (расхождение уходит правее).
//
//   2) В позиции p делаем "прыжок вверх" (bump): ставим САМУЮ МАЛЕНЬКУЮ доступную букву,
//      СТРОГО БОЛЬШУЮ, чем target[p]. Это первое место, где ответ становится больше target.
//
//   3) Всё правее p уже гарантированно больше target — значит остаток заполняем оставшимися
//      буквами ПО ВОЗРАСТАНИЮ (минимальный хвост).
//
//   4) Где делать bump? Мы хотим p как можно ПРАВЕЕ. Поэтому сначала матчим target максимально
//      далеко, а если прыгнуть нельзя (нет буквы строго больше target[p]) — ОТКАТЫВАЕМСЯ влево,
//      возвращаем букву в counts и пробуем прыгнуть там. И так до тех пор, пока не выйдет.
//
//   5) Особый случай: если сматчили target ЦЕЛИКОМ (result == target) — это НЕ строго больше.
//      Значит откатываемся от последней позиции и всё равно делаем bump.
//
// Дошли откатом до начала и прыгнуть негде → ответа нет, возвращаем "".
//
// Сложность: O(n * 26). Память: O(n).
//
// ─────────────────────────────────────────────────────────────────────────────
// ИНВАРИАНТ (делает откат простым):
// Перед попыткой bump на позиции p:
//   - result[0..p-1] уже равен target[0..p-1];
//   - counts содержит РОВНО те буквы, что ещё НЕ использованы (без target[0..p-1]).
// Тогда bump(p) свободно распоряжается позициями p..n-1.
// ─────────────────────────────────────────────────────────────────────────────

var sol = new Solution();
Console.WriteLine(sol.LexGreaterPermutation("abc", "bba"));   // ожидаем "bca"
Console.WriteLine(sol.LexGreaterPermutation("leet", "code")); // ожидаем "eelt"
Console.WriteLine(sol.LexGreaterPermutation("baba", "bbaa")); // ожидаем ""

public class Solution
{
    public string LexGreaterPermutation(string s, string target)
    {
        int n = s.Length;

        // ── Шаг 0. Частоты букв s. ──────────────────────────────────────────────
        // counts[k] = сколько раз буква ('a' + k) доступна для использования.
        int[] counts = new int[26];
        foreach (char ch in s)
            counts[ch - 'a']++;

        char[] result = new char[n];

        // ── Шаг 1. Жадно матчим target как можно дольше. ────────────────────────
        // Пока на позиции i доступна буква target[i] — "занимаем" её (counts--) и ставим
        // в result. Как только буквы target[i] нет — останавливаемся.
        // После цикла: i = длина совпавшего префикса, result[0..i-1] == target[0..i-1].
        int i = 0;
        while (i < n)
        {
            int c = target[i] - 'a';
            if (counts[c] > 0)
            {
                counts[c]--;
                result[i] = target[i];
                i++;
            }
            else
            {
                break; // застряли на позиции i: буквы target[i] в запасе нет
            }
        }

        // ── Шаг 2. Готовим стартовую позицию p для попытки bump-а. ──────────────
        //   - i <  n : застряли на позиции i, туда ещё ничего не поставили,
        //              counts уже корректны → инвариант для p = i выполнен.
        //   - i == n : сматчили target целиком (result == target). Это НЕ строго больше.
        //              Возвращаемся на последнюю позицию: p = n - 1, и ВОЗВРАЩАЕМ её букву
        //              в counts, чтобы восстановить инвариант (позиция p снова "свободна").
        int p;
        if (i < n)
        {
            p = i;
        }
        else
        {
            p = n - 1;
            counts[target[p] - 'a']++; // разжали последнюю совпавшую позицию
        }

        // ── Шаг 3. Откат влево + попытка прыжка. ────────────────────────────────
        // На каждой позиции p пробуем bump. Если не вышло — шаг влево (p--) и ВОЗВРАЩАЕМ
        // букву новой позиции target[p] в counts (разжимаем ещё один символ префикса).
        while (p >= 0)
        {
            if (TryBump(p))
                return new string(result);

            p--;
            if (p >= 0)
                counts[target[p] - 'a']++; // восстановили инвариант для нового p
        }

        // Прыгнуть негде — подходящей перестановки не существует.
        return "";

        // ── Локальная функция: попытка "прыжка" на позиции pos. ─────────────────
        // Ищем САМУЮ МАЛЕНЬКУЮ доступную букву, СТРОГО большую target[pos].
        // Нашли → ставим её в result[pos], уменьшаем counts, заполняем pos+1..n-1
        //          оставшимися буквами ПО ВОЗРАСТАНИЮ, возвращаем true.
        // Не нашли → false (внешний цикл откатится дальше влево).
        bool TryBump(int pos)
        {
            for (int bump = (target[pos] - 'a') + 1; bump < 26; bump++)
            {
                if (counts[bump] == 0)
                    continue;

                // Ставим прыжковую букву на позицию pos.
                counts[bump]--;
                result[pos] = (char)('a' + bump);

                // Заполняем хвост оставшимися буквами по возрастанию → минимальный хвост.
                int idx = pos + 1;
                for (int d = 0; d < 26; d++)
                    while (counts[d]-- > 0)
                        result[idx++] = (char)('a' + d);

                return true;
            }

            return false;
        }
    }
}
